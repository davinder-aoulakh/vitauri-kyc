import React, { useEffect, useState } from 'react';
import { base44 } from '@/api/base44Client';
import { Sheet, SheetContent, SheetHeader, SheetTitle, SheetDescription } from '@/components/ui/sheet';
import { Button } from '@/components/ui/button';
import { toast } from '@/components/ui/use-toast';
import { fetchDiditReport } from '@/lib/diditReport';
import { CheckCircle, Download, FolderPlus, Loader2 } from 'lucide-react';

/**
 * Didit's full report for one session, read on screen. Download lives here too.
 * saveTo = { tenantId, clientId, caseId, currentUser } adds "Save to client file" (used for the business / KYB report).
 */
export default function DiditReportPreview({ open, onOpenChange, sessionId, tenantId, title = 'Didit report', fileName, audit, saveTo, onSaved }) {
  const [src, setSrc] = useState(null);
  const [bytes, setBytes] = useState(null);
  const [error, setError] = useState(null);
  const [saving, setSaving] = useState(false);
  const [saved, setSaved] = useState(false);
  const name = fileName || `Didit_Report_${String(sessionId || '').slice(0, 8)}.pdf`;

  useEffect(() => {
    if (!open || !sessionId) return undefined;
    let alive = true; let url = null;
    setSrc(null); setBytes(null); setError(null); setSaved(false);
    fetchDiditReport(sessionId, tenantId)
      .then((b) => {
        if (!alive) return;
        url = URL.createObjectURL(new Blob([b], { type: 'application/pdf' }));
        setBytes(b); setSrc(url);
        // Who looked at the report (no content)
        if (audit?.tenant_id) {
          base44.entities.AuditEvent.create({
            ...audit, actor_type: 'User', event_type: 'didit_report_viewed',
            before_state: {}, after_state: { didit_session_id: sessionId },
            notes: `${title} opened`,
          }).catch(() => {});
        }
      })
      .catch((e) => { if (alive) setError(e?.message || 'The report could not be loaded.'); });
    return () => { alive = false; if (url) URL.revokeObjectURL(url); };
  }, [open, sessionId]); // eslint-disable-line react-hooks/exhaustive-deps

  async function saveToFile() {
    if (!bytes || !saveTo?.clientId) return;
    setSaving(true);
    try {
      const file = new File([bytes], name, { type: 'application/pdf' });
      const { file_uri } = await base44.integrations.Core.UploadPrivateFile({ file });
      const now = new Date().toISOString();
      // One stored copy per session: a later save replaces the earlier one
      const earlier = await base44.entities.Document.filter({ client_id: saveTo.clientId, didit_session_id: sessionId, source: 'didit_kyb_report' }).catch(() => []);
      const data = {
        tenant_id: saveTo.tenantId, client_id: saveTo.clientId, case_id: saveTo.caseId || undefined,
        doc_type: 'Other', file_name: name, file_url: file_uri, source: 'didit_kyb_report', didit_session_id: sessionId,
        review_status: 'Approved', review_notes: 'Report generated by Didit (business verification)', reviewed_at: now,
      };
      const doc = earlier?.[0] ? await base44.entities.Document.update(earlier[0].id, data) : await base44.entities.Document.create(data);
      await base44.entities.AuditEvent.create({
        tenant_id: saveTo.tenantId, client_id: saveTo.clientId, case_id: saveTo.caseId || undefined,
        actor_user_id: saveTo.currentUser?.id, actor_name: saveTo.currentUser?.full_name, actor_type: 'User',
        event_type: 'didit_report_saved', before_state: {}, after_state: { document_id: doc?.id || earlier?.[0]?.id, didit_session_id: sessionId, replaced: !!earlier?.[0] },
        notes: `${title} saved to the client file`,
      });
      setSaved(true);
      toast({ title: 'Saved to the client file', description: 'The report is in the Documents tab.' });
      onSaved?.();
    } catch (e) {
      toast({ variant: 'destructive', title: 'Could not save the report', description: e?.message });
    } finally {
      setSaving(false);
    }
  }

  return (
    <Sheet open={open} onOpenChange={onOpenChange}>
      <SheetContent side="right" className="w-full sm:max-w-4xl flex flex-col gap-3 z-[60]">
        <SheetHeader>
          <SheetTitle className="pr-8">{title}</SheetTitle>
          <SheetDescription>Report produced by Didit · session {String(sessionId || '').slice(0, 20)}…</SheetDescription>
        </SheetHeader>
        <div className="flex items-center justify-end gap-2 border-b border-border pb-2">
          {saveTo?.clientId && src && (
            <Button size="sm" variant="outline" className="h-8 gap-1.5" onClick={saveToFile} disabled={saving || saved}>
              {saving ? <Loader2 className="h-3.5 w-3.5 animate-spin" /> : saved ? <CheckCircle className="h-3.5 w-3.5 text-emerald-600" /> : <FolderPlus className="h-3.5 w-3.5" />}
              {saved ? 'Saved to client file' : 'Save to client file'}
            </Button>
          )}
          {src && (
            <Button asChild size="sm" className="h-8 gap-1.5">
              <a href={src} download={name}><Download className="h-3.5 w-3.5" /> Download PDF</a>
            </Button>
          )}
        </div>
        {error ? <p className="rounded-md border border-amber-200 bg-amber-50 p-3 text-sm text-amber-900">{error}</p>
          : !src ? <div className="flex flex-1 flex-col items-center justify-center gap-2 text-sm text-muted-foreground"><Loader2 className="h-5 w-5 animate-spin" /> Getting the report from Didit…</div>
            : <iframe title={title} src={src} className="min-h-[70vh] w-full flex-1 rounded-md border border-border" />}
      </SheetContent>
    </Sheet>
  );
}
